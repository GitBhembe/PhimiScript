def create_pdf_bytes(start_date, full_name, student_id):
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=36,
        leftMargin=36,
        topMargin=24,
        bottomMargin=24,
    )
    elements = []
    styles = getSampleStyleSheet()

    # Calculate end date (4 weeks)
    end_date = start_date + timedelta(days=25)

    # --- Logo header (matches the original Word template) ---
    logo_bytes = base64.b64decode(LOGO_B64)
    logo_img = Image(io.BytesIO(logo_bytes), width=2.2 * inch, height=0.85 * inch)
    logo_img.hAlign = "CENTER"
    elements.append(logo_img)
    elements.append(Spacer(1, 8))

    # --- Info fields (plain black text, no color, matches template) ---
    period_str = (
        f"{start_date.strftime('%d %B').upper()} - {end_date.strftime('%d %B %Y').upper()}"
    )
    info_style = ParagraphStyle(
        "Info", parent=styles["Normal"], fontName="Helvetica-Bold", fontSize=10, leading=13
    )
    info_text = f"""
    Name &amp; Surname : {full_name}<br/>
    Student ID : {student_id}<br/>
    Company name : MANNGWE MINING<br/>
    Time Sheet Period : {period_str}<br/>
    """
    elements.append(Paragraph(info_text, info_style))
    elements.append(Spacer(1, 8))

    # Generate 4 Weeks
    curr_date = start_date
    days_map = ["Mon", "Tues", "Wed", "Thurs", "Fri"]

    week_heading_style = ParagraphStyle(
        "WeekHeading",
        parent=styles["Heading3"],
        fontSize=11,
        spaceBefore=4,
        spaceAfter=2,
    )

    for week_num in range(1, 5):
        # Matches the template's quirk: "Week: 1" then "WEEK: 2/3/4"
        week_label = f"Week: {week_num}" if week_num == 1 else f"WEEK: {week_num}"
        elements.append(Paragraph(f"<b>{week_label}</b>", week_heading_style))

        table_data = [
            [
                "Day",
                "Date",
                "Time In",
                "Time Out",
                "Supervisor Signature",
            ]
        ]

        for day_idx in range(5):
            date_formatted = curr_date.strftime("%d/%m/%Y")
            table_data.append(
                [
                    days_map[day_idx],
                    date_formatted,
                    "07h00",
                    "16h00",
                    "",
                ]
            )
            curr_date += timedelta(days=1)

        # Skip weekend to next Monday
        curr_date += timedelta(days=2)

        t = Table(table_data, colWidths=[50, 90, 80, 80, 200], rowHeights=16)
        t.setStyle(
            TableStyle(
                [
                    ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
                    ("FONTSIZE", (0, 0), (-1, -1), 9),
                    ("TEXTCOLOR", (0, 0), (-1, -1), colors.black),
                    ("ALIGN", (0, 0), (-1, -1), "LEFT"),
                    ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
                    ("GRID", (0, 0), (-1, -1), 0.75, colors.black),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
                    ("TOPPADDING", (0, 0), (-1, -1), 2),
                    ("LEFTPADDING", (0, 0), (-1, -1), 4),
                ]
            )
        )

        elements.append(t)
        elements.append(Spacer(1, 6))

    footer_style = ParagraphStyle(
        "Footer", parent=styles["Normal"], fontSize=10, leading=13, spaceBefore=6
    )
    footer_text = (
        "Supervisor Name &amp; Surname :<br/><br/>"
        "Supervisor Signature :"
    )
    elements.append(Paragraph(footer_text, footer_style))

    doc.build(elements)
    buffer.seek(0)
    return buffer


